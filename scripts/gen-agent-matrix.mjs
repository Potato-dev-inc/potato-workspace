#!/usr/bin/env node
// Writes docs/AGENT-MATRIX.md from the conformance runner's agent-matrix.json.
//
// One row per agent/level (a fake target), one column per behaviour. Each cell says the result and how it was
// proven: fake (a scripted fake agent), fixture (a recorded real transcript) or real (a live run). A live proof
// also carries the date and the agent version when the JSON has them.
//
//   node scripts/gen-agent-matrix.mjs                       read the runner's JSON, write docs/AGENT-MATRIX.md
//   node scripts/gen-agent-matrix.mjs --check               exit 1 when the doc is out of date
//   node scripts/gen-agent-matrix.mjs --json <file|->       another JSON (- reads stdin)
//   node scripts/gen-agent-matrix.mjs --out <file>          another output file
//
// The JSON is written by `cargo test --lib -- conformance_matrix_json_is_written` into the cargo target folder
// (CARGO_TARGET_DIR, else packages/app/src-tauri/target).

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const DEFAULT_OUT = join(repoRoot, 'docs', 'AGENT-MATRIX.md');

// Plain names for the fake targets, in the order the runner lists them.
const TARGET_WORDS = {
  native: 'Chat agent that keeps the rules',
  native_bad: 'Chat agent that breaks them (must fail)',
  json: 'One-task agent, JSON output',
  text: 'One-task agent, plain text',
  terminal_only: 'Terminal-only agent',
};

export function defaultJsonPath(env = process.env) {
  const target = env.CARGO_TARGET_DIR ? resolve(env.CARGO_TARGET_DIR) : join(repoRoot, 'packages', 'app', 'src-tauri', 'target');
  return join(target, 'agent-matrix.json');
}

function escapeCell(text) {
  return String(text ?? '').replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');
}

// One cell: result + how it was proven (+ date and version when a live proof has them).
export function cellText(cell) {
  if (!cell || cell.result === 'not_claimed') return '-';
  const how = [cell.mark ?? 'fake', cell.date, cell.version].filter(Boolean).join(' ');
  const word = cell.result === 'pass' ? 'pass' : cell.result === 'fail' ? 'FAIL' : String(cell.result);
  return `${word} (${how})`;
}

export function targetsOf(matrix) {
  const seen = [];
  for (const row of matrix.vectors) for (const name of Object.keys(row.cells)) if (!seen.includes(name)) seen.push(name);
  return seen;
}

export function render(matrix) {
  const rows = matrix.vectors;
  const targets = targetsOf(matrix);
  const out = [];
  out.push('# Agent matrix', '');
  out.push("<!-- Generated by scripts/gen-agent-matrix.mjs from the conformance runner's agent-matrix.json. Do not edit by hand. -->", '');
  out.push('What each kind of agent was proven to do. One row per agent kind, one column per behaviour (the ids are explained below the table).', '');
  out.push('Each cell says the result and how it was proven:', '');
  out.push('- `pass (fake)` or `FAIL (fake)`: a scripted fake agent was run through the real chat code.');
  out.push('- `(fixture ...)`: a recorded transcript of a real agent was replayed.');
  out.push('- `(real <date> <version>)`: a live run against the real agent, on that date, at that version.');
  out.push('- `-`: the behaviour is not claimed for this kind of agent, so it was not run.', '');
  out.push('To regenerate: `cargo test --lib -- conformance_matrix_json_is_written`, then `node scripts/gen-agent-matrix.mjs`. To check it is fresh: `node scripts/gen-agent-matrix.mjs --check`, or `cargo test --lib -- --ignored matrix_doc_is_fresh`.', '');
  out.push('## Results', '');
  const ids = rows.map((r) => r.id);
  out.push(`| Agent kind | ${ids.join(' | ')} |`);
  out.push(`| --- | ${ids.map(() => '---').join(' | ')} |`);
  for (const target of targets) {
    const label = TARGET_WORDS[target] ?? target.replace(/_/g, ' ');
    out.push(`| ${escapeCell(label)} (\`${target}\`) | ${rows.map((r) => escapeCell(cellText(r.cells[target]))).join(' | ')} |`);
  }
  out.push('', '## Behaviours', '');
  out.push('| Id | What is checked | Capability it proves |', '| --- | --- | --- |');
  for (const r of rows) out.push(`| ${r.id} | ${escapeCell(r.title)} | ${escapeCell((r.claims ?? []).join(', ') || '-')} |`);
  const failing = [];
  for (const r of rows) for (const t of targets) if (r.cells[t]?.result === 'fail' && r.cells[t].why) failing.push(`- ${r.id} on \`${t}\`: ${escapeCell(r.cells[t].why)}`);
  if (failing.length) out.push('', '## Why the failing cells fail', '', ...failing);
  const notes = matrix.notes ?? [];
  if (notes.length) out.push('', '## Not run', '', ...notes.map((n) => `- \`${n.target}\`: ${escapeCell(n.note)}`));
  out.push('');
  return out.join('\n');
}

function parseArgs(argv) {
  const opts = { check: false, json: null, out: DEFAULT_OUT };
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === '--check') opts.check = true;
    else if (argv[i] === '--json') opts.json = argv[++i];
    else if (argv[i] === '--out') opts.out = resolve(argv[++i]);
    else throw new Error(`unknown argument ${argv[i]}`);
  }
  return opts;
}

export function main(argv = process.argv.slice(2), env = process.env) {
  const opts = parseArgs(argv);
  const jsonPath = opts.json ?? defaultJsonPath(env);
  const source = jsonPath === '-' ? readFileSync(0, 'utf8') : existsSync(jsonPath) ? readFileSync(jsonPath, 'utf8') : null;
  if (source === null) {
    console.error(`gen-agent-matrix: ${jsonPath} not found. Run: cargo test --lib -- conformance_matrix_json_is_written`);
    return 1;
  }
  const doc = render(JSON.parse(source));
  const current = existsSync(opts.out) ? readFileSync(opts.out, 'utf8').replace(/\r\n/g, '\n') : '';
  if (opts.check) {
    if (current === doc) return 0;
    console.error(`gen-agent-matrix: ${opts.out} is out of date. Run: node scripts/gen-agent-matrix.mjs`);
    return 1;
  }
  writeFileSync(opts.out, doc);
  console.log(`wrote ${opts.out}`);
  return 0;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) process.exit(main());
