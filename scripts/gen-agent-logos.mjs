#!/usr/bin/env node
// Writes packages/app/src/lib/agentLogoData.ts: only the Simple Icons (CC0 1.0) we draw, as SVG path data.
//   node scripts/gen-agent-logos.mjs           write the file
//   node scripts/gen-agent-logos.mjs --check   exit 1 when the file is out of date
// Needs the devDependencies `simple-icons` and `simple-icons-13` (OpenAI was removed from newer releases, so
// that one icon comes from 13.21.0, which is still CC0). Not in Simple Icons at all: Kilo, Aider, Goose.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const out = join(resolve(dirname(fileURLToPath(import.meta.url)), '..'), 'packages', 'app', 'src', 'lib', 'agentLogoData.ts');

// logo key -> [package, export name]
const ICONS = {
  claude: ['simple-icons', 'siClaude'],
  openai: ['simple-icons-13', 'siOpenai'],
  cursor: ['simple-icons', 'siCursor'],
  gemini: ['simple-icons', 'siGooglegemini'],
  copilot: ['simple-icons', 'siGithubcopilot'],
  opencode: ['simple-icons', 'siOpencode'],
  kimi: ['simple-icons', 'siKimi'],
  qwen: ['simple-icons', 'siQwen'],
  mistral: ['simple-icons', 'siMistralai'],
  cline: ['simple-icons', 'siCline'],
};

const lines = [
  '// GENERATED by scripts/gen-agent-logos.mjs. Do not edit by hand.',
  '// Agent logos from Simple Icons (https://simpleicons.org), CC0 1.0. Trademarks belong to their owners.',
  '// All icons are 24x24 single-path SVGs.',
  '',
  'export interface AgentLogoData {',
  '  title: string;',
  '  hex: string;',
  '  path: string;',
  '}',
  '',
  'export const AGENT_LOGO_DATA: Record<string, AgentLogoData> = {',
];
for (const [key, [pkg, name]] of Object.entries(ICONS)) {
  const icon = require(pkg)[name];
  if (!icon) throw new Error(`${name} is not in ${pkg}`);
  lines.push(`  ${key}: { title: ${JSON.stringify(icon.title)}, hex: ${JSON.stringify(icon.hex)}, path: ${JSON.stringify(icon.path)} },`);
}
lines.push('};', '');
const text = lines.join('\n');
if (process.argv.includes('--check')) {
  let cur = '';
  try { cur = readFileSync(out, 'utf8'); } catch { /* missing */ }
  if (cur !== text) { console.error('agentLogoData.ts is out of date: run node scripts/gen-agent-logos.mjs'); process.exit(1); }
} else {
  writeFileSync(out, text);
  console.log(`wrote ${out}`);
}
